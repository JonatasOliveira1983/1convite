export function getTrilhaPorTema(tema) {
  const chave = (tema || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  return TRILHAS_DATA[chave] || TRILHAS_DATA.ansiedade;
}

export function getConteudoDiaTrilha(tema, diaNumero = 1) {
  const trilha = getTrilhaPorTema(tema);
  const dias = trilha.dias;
  // Se o dia pedido for maior que a lista base, gera dinamicamente mantendo a progressão
  const diaExistente = dias.find(d => d.dia === diaNumero);
  if (diaExistente) return diaExistente;

  // Ciclo dos dias
  const index = (diaNumero - 1) % dias.length;
  const base = dias[index];
  return {
    dia: diaNumero,
    titulo: `${base.titulo} • Parte ${Math.floor((diaNumero - 1) / dias.length) + 1}`,
    versiculo: base.versiculo,
    reflexao: base.reflexao,
    acao_pratica: base.acao_pratica
  };
}
