function normalizeLang(lang) {
  if (lang === "en" || lang === "es") return lang;
  return "pt";
}
function getLocale(lang) {
  const l = normalizeLang(lang);
  return l === "en" ? "en-US" : l === "es" ? "es-ES" : "pt-BR";
}
function htmlLang(lang) {
  const l = normalizeLang(lang);
  return l === "en" ? "en" : l === "es" ? "es" : "pt-BR";
}
function formatDate(lang, date, opts = { year: "numeric", month: "long", day: "numeric" }) {
  const d = typeof date === "string" ? new Date(date) : date;
  if (Number.isNaN(d.getTime())) return "";
  return d.toLocaleDateString(getLocale(lang), opts);
}
function formatMoney(lang, cents, currency = "BRL") {
  return (cents / 100).toLocaleString(getLocale(lang), { style: "currency", currency });
}
